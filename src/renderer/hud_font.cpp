HudFontAtlas buildHudFontAtlas() {
    HudFontAtlas atlas;
    atlas.width = kHudAtlasWidth;
    atlas.height = kHudAtlasHeight;
    atlas.pixels.assign(static_cast<std::size_t>(atlas.width) * atlas.height, 0);

    for (const GlyphDef& glyph : kGlyphs) {
        const int code = static_cast<unsigned char>(glyph.code);
        if (code < 32 || code > 95) {
            continue;  // вне покрываемого диапазона
        }
        const uint32_t cell = static_cast<uint32_t>(code - 32);
        const uint32_t cellX = (cell % kHudAtlasCols) * kHudCellW;
        const uint32_t cellY = (cell / kHudAtlasCols) * kHudCellH;
        for (uint32_t row = 0; row < kHudGlyphH; ++row) {
            const char* line = glyph.rows[row];
            for (uint32_t col = 0; col < kHudGlyphW; ++col) {
                if (line[col] != '#') {
                    continue;
                }
                const uint32_t x = cellX + col;
                const uint32_t y = cellY + row;
                atlas.pixels[static_cast<std::size_t>(y) * atlas.width + x] = 255;
            }
        }
    }
    return atlas;
}

