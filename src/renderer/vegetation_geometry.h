#pragma once

// vegetation_geometry — процедурная геометрия растений.
//
// Почему процедурная, а не OBJ: в assets/ лежит один cube.obj, а видов
// растительности нужно минимум четыре (хвойное, лиственное, куст, трава), и
// каждый должен выглядеть по-разному в зависимости от климата. Тот же куб,
// растянутый по Y, даёт «палку с кубом на макушке», а не растение.
//
// ГЛАВНАЯ КОНВЕНЦИЯ — содержимое uv у вершины:
//
//   uv.x — ЖИБКОСТЬ, 0..1. Ноль у жёстких частей (ствол, камень) и единица у
//          самых кончиков. Читается в shaders/triangle.vert: чем больше
//          значение, тем сильнее ветка гнётся на ветру. Ноль означает
//          «не гнуться», поэтому рельеф (uv = 0) не дышит вместе с травой.
//   uv.y — ВЫСОТА ВНУТРИ РАСТЕНИЯ, 0 у земли, 1 у макушки. Смещение на ветру
//          умножается на квадрат этого значения, иначе ствол у самой земли
//          двигался бы вместе с кроной и растение казалось бы выдвинутым из
//          земли целиком.
//
// Именно поэтому у геометрии ниже заполняется uv, а не только цвет: без uv
// ветер либо не будет работать вовсе, либо будет шевелить рельеф.

#include <cstdint>

#include <glm/glm.hpp>

#include "renderer/model_loader.h"

namespace renderer::vegetation {

// === Параметры одного вида ===

// Общие для всех видов параметры «маленького растения» (куст, трава).
struct SmallSpec {
    // Высота от земли до макушки, м.
    float height{0.6f};
    // Горизонтальный размах, м. Задаёт ширину куста или пучка травы.
    float spread{0.5f};
    // Цвет альбедо (0..1). У растительности цвет в вершине, а не текстура.
    glm::vec3 color{0.30f, 0.45f, 0.18f};
    // Цвет верхушки/кончика: у травы и хвои кончики светлее и суше, чем
    // основание. Интерполируется по uv.y.
    glm::vec3 tipColor{0.55f, 0.62f, 0.28f};
    // Склонность к снегу 0..1: у травы снег почти не лежит (мало высоты),
    // у куста — тоже, у кроны дерева — заметно.
    float snowBias{0.1f};
    // Максимальная гибкость uv.x. Трава гнётся почти целиком (1.0), куст —
    // слабее, у куста ветки короткие.
    float maxFlex{0.8f};
};

// Хвойное: ствол и ярусы хвои, сужающиеся кверху. Растёт в холодном и
// влажном климате, поэтому tipColor холоднее зелёного.
SmallSpec coniferSpec(std::uint32_t seed);
// Лиственное: ствол, несколько ветвей и округлая крона. Умеренный климат.
SmallSpec broadleafSpec(std::uint32_t seed);
// Куст: низкая комковатая крона без ствола. Засуха и граница леса.
SmallSpec shrubSpec(std::uint32_t seed);
// Пучок травы: несколько узких blades. Везде, где не вода и не лёд.
SmallSpec grassSpec(std::uint32_t seed);

// Геометрия вида. Base внутри вида — Y=0, поэтому позиция инстанса
// совпадает с точкой земли, а Primitive считает AABB по геометрии.
//
// Каждая функция детерминирована по seed: один и тот же seed всегда даёт
// одно и то же растение, что позволяет рассеву быть воспроизводимым.
ModelData makeConifer(const SmallSpec& spec);
ModelData makeBroadleaf(const SmallSpec& spec);
ModelData makeShrub(const SmallSpec& spec);
ModelData makeGrassTuft(const SmallSpec& spec);

// Габариты СТВОЛА — их используют и генератор геометрии, и коллизии (см.
// world::VegetationScatter::TreeCollider). Отдельные функции не «для удобства»:
// если бы коллизия считала свой радиус по своей формуле, она рано или поздно
// разошлась бы с видимым стволом, и игрок стал бы упираться в воздух там,
// где ствола нет, или проходить сквозь него там, где он есть.
//
// Радиус ствола в метрах.
float trunkRadius(const SmallSpec& spec, bool broadleaf);
// Высота, до которой ствол твёрдый, в метрах: у лиственного она обрывается
// заметно ниже кроны (ствол расходится ветвями), у хвойного почти до макушки.
float trunkTopHeight(const SmallSpec& spec, bool broadleaf);

// Габариты геометрии, нужные culling'у. Считаются из вершин, а не задаются
// константой: у «палки с кубом» радиус 2.6 при высоте 4.1 и основании в Y=0
// не покрывал крону, и деревья выпадали из кадра на самом виду — потому что
// AABB строился вокруг точки ЗЕМЛИ, а не вокруг тела растения.
struct Bounds {
    glm::vec3 min{0.0f};
    glm::vec3 max{0.0f};
};
Bounds boundsOf(const ModelData& model);

}  // namespace renderer::vegetation
