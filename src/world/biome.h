#pragma once

// Биомы ландшафта: пустыня, лес, тундра, горы. Биом — это не метка, а
// непрерывная смесь: в точке ландшафта одновременно «присутствуют» все четыре
// биома с разными весами, поэтому границы между ними не видно (нет ступенек
// на цвете вершин).
//
// Модуль ничего не знает про шум, карту высот и Vulkan — на входе только
// три числа (высота, температура, влажность), на выходе веса, цвет и
// «склонность к снегу». Температура здесь — среднегодовая (см. world::Climate:
// annualMeanTemperatureAt), а не текущая: иначе зимой весь ледник стал бы
// пустыней, а летом тундра — лесом. Сезон учитывается отдельно, в шейдере.
//
// Три уровня API:
//   * getBiome()      — доминирующий биом, одно значение (для логов и правил);
//   * sampleBiome()   — полная смесь BiomeBlend (для цвета и снега);
//   * biomeColor()    — базовый цвет одного биома.

#include <algorithm>
#include <cstddef>

#include <glm/glm.hpp>

namespace world {

// Тип биома. Порядок значений совпадает с индексом в весах BiomeBlend, поэтому
// kBiomeCount всегда равен числу биомов.
enum class Biome : std::size_t {
    Desert = 0,     // жарко и сухо
    Forest = 1,     // умеренно, влажно
    Tundra = 2,     // холодно
    Mountains = 3,  // высоко (перекрывает остальные по высоте)
};

inline constexpr std::size_t kBiomeCount = 4;

// Границы биомов и ширины переходов между ними. Значения по умолчанию
// подобраны под ландшафт TerrainGenerator (amplitude = 26, то есть высоты
// примерно в [-26, +26]) и под климат средней полосы.
struct BiomeParams {
    // --- Горы: по высоте ---
    // Ниже mountainStart гор нет вовсе, выше mountainEnd — только горы.
    // Между ними вклад гор плавно растёт от 0 до 1.
    //
    // Абсолютные значения — только запасной вариант. Обычно высота задаётся
    // долями от диапазона карты высот (mountainStartFraction /
    // mountainEndFraction, см. fitBiomeHeights), потому что реальный размах
    // шума не равен amplitude: у TerrainGenerator с gain = 0.4 шум занимает
    // примерно половину заявленной амплитуды, и абсолютный порог в 16 единиц
    // оказался бы недостижимым — гор не было бы вообще.
    float mountainStart{16.0f};
    float mountainEnd{24.0f};
    // Доли от диапазона [minHeight, maxHeight], где начинаются и заканчиваются
    // горы: 0 — самая низкая точка карты, 1 — самая высокая.
    float mountainStartFraction{0.65f};
    float mountainEndFraction{0.92f};

    // --- Тундра: по холоду ---
    // tundraWarm — температура, при которой вклад тундры ещё нулевой;
    // tundraCold — при которой тундра доминирует.
    float tundraWarm{3.0f};
    float tundraCold{-4.0f};

    // --- Пустыня: по жаре И сухости ---
    // Один жар без сухости пустыни не даёт: жара при нормальной влажности — это
    // лес. desertCool — прохладно (пустыни нет), desertHot — жарко.
    float desertCool{15.0f};
    float desertHot{28.0f};

    // --- Сухость: половина условия пустыни ---
    // humidityMoist — влажность, при которой жара уже не даёт пустыни;
    // humidityDry — сухость, при которой пустыня максимальна.
    float humidityMoist{0.45f};
    float humidityDry{0.18f};

    // --- Снег ---
    // snowMelt — выше этой температуры снег не лежит вообще;
    // snowFreeze — ниже неё снег лежит круглый год.
    float snowMelt{14.0f};
    float snowFreeze{2.0f};
    // Насколько снежность растёт от холода (1 — целиком от температуры).
    float snowFromCold{0.7f};
    // Вклад высоты в снежность сверх температуры: вершины гор снежны и там,
    // где внизу тепло. Держится меньше snowFromCold намеренно — иначе вершины
    // оказываются белыми круглый год и сезоны на них не читаются.
    float mountainSnow{0.25f};
    // Минимальная доля леса: страховка от вырожденного случая, когда все три
    // индикатора (холод, жара, сухость) дали нули и нормировать нечего.
    // Заодно слегка окрашивает края пустынь и гор в зелень.
    float forestFloor{0.04f};

    // --- Лёд ---
    // Ледник — это не биом, а покрытие: он лежит ПОВЕРХ пустыни, леса и гор
    // одинаково (Гренландия, Памир). Поэтому лёд не добавляет веса ни одному
    // биому, а подмешивается к цвету и снежности отдельно.
};

// Смесь биомов в одной точке ландшафта: веса (в сумме 1), производный цвет
// альбедо и склонность места к снегу.
class BiomeBlend {
public:
    BiomeBlend() = default;

    // Веса нормализованы (в сумме 1), поэтому color() — уже готовое альбедо.
    float weight(Biome biome) const;
    void setWeight(Biome biome, float value);

    // Биом с наибольшим весом — «победитель» смеси.
    Biome dominant() const;

    // Альбедо точки: взвешенная сумма цветов биомов. Так как веса плавные,
    // границы биомов дают плавный же переход цвета.
    glm::vec3 color() const;

    // Насколько место склонно к снегу, 0..1:
    //   0 — снег не лежит никогда (ниже снеговой границы, пустыня);
    //   1 — снег лежит круглый год (тундра, вершины гор).
    // Сезонная составляющая не входит в число: её шейдер подмешивает сам,
    // поэтому ландшафт не перестраивается при смене сезона.
    float snowBias() const { return snowBias_; }
    void setSnowBias(float value) { snowBias_ = value; }

    // Лёд поверх смеси, 0..1: подмешивается к цвету и поднимает снежность до
    // единицы (на леднике снег лежит круглый год). Вынесено отдельно от весов
    // биомов, потому что ледник не «заменяет» биом, а покрывает его.
    float ice() const { return ice_; }
    void setIce(float value) { ice_ = std::clamp(value, 0.0f, 1.0f); }

private:
    float weights_[kBiomeCount]{1.0f, 0.0f, 0.0f, 0.0f};
    float snowBias_{0.0f};
    float ice_{0.0f};
};

// Доминирующий биом точки по высоте, среднегодовой температуре и влажности.
// Для правил и логов; для цвета нужен sampleBiome() — он даёт смесь.
Biome getBiome(float height, float temperature, float humidity,
               const BiomeParams& params = BiomeParams{});

// Плавная смесь биомов: веса, цвет и снежность. Основная функция раскраски.
// ice — доля вечного льда 0..1 (world::Climatology::iceAt). Нужен, чтобы
// ледник был белым поверх любого биома и держал снег круглый год; без него
// поведение прежнее.
BiomeBlend sampleBiome(float height, float temperature, float humidity,
                       const BiomeParams& params = BiomeParams{}, float ice = 0.0f);

// Пересчитывает высотные пороги params под фактический диапазон карты высот
// [minHeight, maxHeight], используя mountainStartFraction/mountainEndFraction.
// Вызывается world::Terrain сразу после генерации — иначе пороги зависели бы
// от amplitude генератора, а не от реального рельефа, и на части сидов гор не
// было бы вовсе. При вырожденном диапазоне (плоская карта) пороги
// усредняются, чтобы не получить деления на ноль.
void fitBiomeHeights(BiomeParams& params, float minHeight, float maxHeight);

// Базовое альбедо биома (без освещения и без снега).
glm::vec3 biomeColor(Biome biome);

// Имя биома для логов и отладки.
const char* biomeName(Biome biome);

}  // namespace world
