#pragma once

// vegetation_scatter — климатозависимый рассев растительности по миру.
//
// Отделяет ВОПРОС «что растёт в этой точке» (мир: климат, высота, вода) от
// ВОПРОСА «как это нарисовать» (renderer::InstancedRenderer). Renderer о
// климате не знает и знать не должен: иначе его пришлось бы переписывать
// вместе с моделью климата.
//
// Ключевое отличие от прежнего spawnTrees: вид и плотность выбираются по
// КЛИМАТУ точки. Прежний рассев ставил одинаковую «палку с кубом» по сетке и
// ни разу не спрашивал, пустыня это, тайга или долина.

#include <array>
#include <cmath>
#include <cstdint>
#include <vector>

#include "core/double_math.h"
#include "renderer/instanced_renderer.h"
#include "renderer/vegetation_geometry.h"
#include "renderer/vulkan_base.h"

namespace world {

// Всё, что рассеву нужно знать о точке земли. Заполняется вызывающим
// (см. SiteSampler): рассев не должен сам ходить в ChunkManager, иначе он
// становится зависимым от порядка стриминга чанков.
struct SiteSample {
    float height{0.0f};          // высота рельефа, м
    float temperature{15.0f};    // ℃
    float precipitation{0.4f};   // осадки 0..1 (нормированные)
    float humidity{0.4f};        // влажность 0..1
    float dryness{0.2f};         // сухость/каменистость почвы 0..1
    float ice{0.0f};             // доля лёда 0..1
    float continentality{0.3f};  // материковость 0..1
    float aboveSea{10.0f};      // высота над локальным уровнем моря, м

    // NaN по высоте означает «точка недоступна» (чанк не загружен): сэмплер
    // обязан вернуть NaN, а не 0, иначе рассев посадит лес в пустоте.
    bool valid() const noexcept { return std::isfinite(height); }
};

// Функция сэмплирования точки. Указатель, а не лямбда: captureless-лямбда
// преобразуется в указатель константно, но тип оператора преобразования —
// указатель на функцию без аргументов, и он не совпал бы с SiteSampler.
using SiteSampler = SiteSample (*)(double globalX, double globalZ, void* userData);

class VegetationScatter {
public:
    // Виды растительности. Conifer=1 и дальше — индексы используются как
    // индексы в массивах, поэтому None обязан быть 0.
    enum class Species : std::size_t {
        None = 0,
        Conifer = 1,   // хвойное: холодно и влажно
        Broadleaf = 2, // лиственное: тепло и влажно
        Shrub = 3,     // куст: засуха, граница леса, холод
        Grass = 4,     // трава: почти везде
    };
    static constexpr std::size_t kSpeciesCount = 5;

    // Минимальный радиус ствола для коллизии, м. У ели высотой 12 м ствол
    // по формуле — 22 см, а капсула игрока шире. С тонким стволом игрок
    // «проезжал» бы сквозь дерево по касательной, задевая его ровно на своём
    // радиусе: упираться в ствол можно было бы только прицельно в центр.
    static constexpr float kMinTrunkRadius = 0.35f;

    struct Config {
        // ОТНОШЕНИЯ видов, а не абсолютные доли: при выборе вида веса
        // нормируются, поэтому важно лишь их соотношение. Характерный мир:
        // много травы, заметно меньше кустов, деревья самые редкие (дерево —
        // самая тяжёлая геометрия из всех видов).
        //
        // ВАЖНО про «уменьшить деревья вдвое»: общая КОЛИЧЕСТВО растений задаётся
        // не этими весами, а покрытием (coverageAt), поэтому уменьшение
        // treeDensity уменьшает ДОЛЮ деревьев, а не их абсолютное число. Отношение
        // нелинейно: при tree = 18% весов половина веса даёт не 50%, а ~55%
        // деревьев, потому что знаменатель нормировки тоже меняется. Считать
        // точное «вдвое» пришлось бы подгонкой константы под конкретный климат,
        // и в другом биоме она разъехалась бы. Поэтому здесь честная половина
        // ВЕСА, а фактическое число видно в логе рассева.
        float treeDensity{0.03f};
        float shrubDensity{0.22f};
        float grassDensity{0.68f};
        // Дальность, дальше которой вид не сажается ВООБЩЕ, м.
        //
        // Трава — 80% всех объектов (36 из 53 тысяч при радиусе 260 м), и
        // дальше ~70 м она меньше пикселя: ни одного вклада в картинку, но
        // полная цена объекта, инстанса, AABB и отсечения каждый кадр.
        // Деревья и кусты остаются по всему кругу — их видно.
        float treeMaxDistanceMeters{100000.0f};
        float shrubMaxDistanceMeters{170.0f};
        float grassMaxDistanceMeters{70.0f};
        // С какой доли предельной дальности начинается вымирание вида. Жёсткий
        // обрыв читался бы кольцом на открытой местности, поэтому вид не
        // исчезает разом, а прореживается.
        float fadeStartFraction{0.6f};
        // Ниже этой высоты над уровнем моря ничего не сажаем: пляж, болото.
        float minAboveSea{1.5f};
        // Насколько «жизнеспособно» место, переводится в долю занятых ячеек
        // (см. coverageAt). Три — потому что покрытие становится сплошным
        // примерно при vigor >= 1/3, а ниже остаются проплешины разной
        // величины: именно они отличают лес от ковра.
        float coverageGain{3.0f};
        // Сколько ГЕОМЕТРИЧЕСКИХ вариантов на вид. Каждый вариант — свой mesh
        // и свой draw call, поэтому два варианта дают вдвое больше
        // разнообразия формы за вдвое больше вызовов. Больше двух — плохой
        // обмен: читается уже как «другой вид», а стоит как лишний вызов.
        std::uint32_t variantsPerSpecies{2};
        // Базовый seed геометрии. Разные варианты одного вида отличаются
        // пропорциями и оттенком, иначе лес из двух тысяч одинаковых деревьев
        // читается как копипаст. При пересборке мира (новый VulkanBase) виды
        // выглядят так же, потому что seed фиксирован.
        std::uint32_t geometrySeed{20240517u};
    };

    // Два конструктора вместо `explicit VegetationScatter(Config = Config{})`:
    // значение по умолчанию вида Config{} в теле класса сослаться на ещё не
    // завершённый вложенный тип нельзя — ровно та же причина, по которой в
    // world::Climate объявлено два конструктора.
    VegetationScatter();
    explicit VegetationScatter(const Config& config);

    // Выбор вида в точке по климату. Отдельная публичная функция: это
    // содержательная часть алгоритма, её стоит уметь проверить, не создавая
    // InstancedRenderer и VulkanBase.
    //
    // roll — число 0..1, различающее виды с близкими весами (в тайге на
    // границе хвои и листвы). Передаётся ЯВНЫМ параметром, а не берётся из
    // ГПСЧ внутри: только так функция остаётся чистой и воспроизводимой —
    // перестроение рассева при движении игрока обязано дать тот же лес.
    Species speciesAt(const SiteSample& site, float roll = 0.5f) const;

    // Доля ячеек сетки, ЗАНЯТЫХ растением, 0..1. Это отдельная от выбора
    // вида величина, и разделение принципиально: если решать только вид,
    // то каждая ячейка сетки получает растение, и земля выглядит ковром,
    // уложенным по линейке — с равномерными промежутками в 2 м, которые
    // видно с высоты игрока. Плотность обязана быть вероятностью, а не
    // следствием того, что «вид выбрался».
    //
    // Пустота — тоже результат: у пустыни и тундры покров стремится к нулю.
    float coverageAt(const SiteSample& site) const;

    // Предельная дальность рассева для вида, м. Видно, что деревья не
    // ограничены кругом рассева, а трава ограничена.
    float maxDistanceFor(Species species) const noexcept;

    struct ScatterRequest {
        awdm::dvec3 centerGlobal{0.0};
        // Радиус области рассева, м. Область КРУГЛАЯ, а не квадратная.
        double radiusMeters{220.0};
        // Шаг сетки кандидатов, м. Число ячеек растёт как (2R/cell)² и
        // каждая ячейка требует одного сэмплирования климата, поэтому это
        // главный регулятор стоимости рассева.
        double cellSizeMeters{2.0};
        // Потолок объектов. Защита от «леса на 10 кв. км»: рассев обрезает
        // по cap, а не пытается выделить память на миллион объектов.
        std::size_t maxObjects{90000};
    };

    // Расставить растительность в круге радиуса request.radiusMeters.
    // Возвращает число расставленных объектов. Детерминирован по координатам
    // ячеек: один и тот же участок всегда даёт один и тот же результат
    // независимо от порядка обхода и от того, как он поделён на вызовы.
    std::size_t scatter(const ScatterRequest& request, SiteSampler sampler, void* userData,
                        renderer::VulkanBase& renderer, renderer::InstancedRenderer& target);

    // Твёрдый ствол дерева. Рассев собирает их ПОСЛЕ scatter() отдельным
    // проходом, потому что коллизии нужны не всем растениям: игрок упирается
    // в ствол дерева, но не должен упираться в куст и тем более в траву.
    // Радиус и высота берутся из той же формулы, что и у видимого ствола
    // (renderer::vegetation::trunkRadius/trunkTopHeight), иначе игрок стал бы
    // упираться в воздух.
    struct TreeCollider {
        awdm::dvec3 baseGlobal{0.0};  // точка у земли
        float radius{0.0f};
        float height{0.0f};
    };

    // Коллайдеры стволов последнего scatter(). Пусто до первого вызова.
    // Ссылка действительна до следующего scatter() — буфер переиспользуется,
    // как и остальные рабочие буферы рассева.
    const std::vector<TreeCollider>& treeColliders() const noexcept { return treeColliders_; }

    const Config& config() const noexcept { return config_; }

private:
    // Плоский индекс примитива вида: (species - 1) * variants + variant.
    // Пуст, пока scatter() не вызвал ensurePrimitives(): индексы зависят от
    // того, что уже загружено в конкретный VulkanBase, и не переживают его
    // пересоздание.
    const std::vector<std::uint16_t>& ensurePrimitives(renderer::VulkanBase& renderer,
                                                        renderer::InstancedRenderer& target);

    static renderer::ModelData makeGeometry(Species species,
                                            const renderer::vegetation::SmallSpec& spec);
    static renderer::vegetation::SmallSpec specFor(Species species, std::uint32_t seed);
    static float speciesScale(Species s, float r) noexcept;
    static glm::vec3 tintFor(Species s, const SiteSample& site, float r) noexcept;

    Config config_;
    std::vector<std::uint16_t> primitives_;
    // Буфер коллайдеров последнего рассева, переиспользуется между вызовами.
    std::vector<TreeCollider> treeColliders_;
    bool primitivesReady_{false};    // ГПСЧ не используется: выбор вида и варианта идёт от детерминированного
    // хеша координат точки (cellRandom), поэтому «тот же лес» получается
    // при любом порядке обхода и на любой машине.
};

}  // namespace world
