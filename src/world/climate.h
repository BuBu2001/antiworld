#pragma once

// Климат мира: течение времени года, сезон, температура и влажность.
//
// Модель намеренно простая и полностью аналитическая — состояние это две
// фазы (фаза года и время суток), поэтому климат детерминирован, его можно
// перемотать вперёд-назад и он не «дрейфует» от числа шагов интегрирования.
// Никакого шума и накопления ошибок: update() просто двигает фазы.
//
// Температура раскладывается на четыре слагаемых (все в градусах Цельсия):
//   сезонное   — косинус с периодом в год, максимум в середине лета;
//   высотное   — падение с высотой (градиент температуры), из-за чего вершины
//                холоднее низин и попадают в горы/тундру;
//   широтное   — линейный градиент по X (северная сторона карты холоднее);
//   суточное   — косинус с периодом в сутки.
// Первые три меняются только по сезону, суточное — по времени суток.
//
// Разделение «среднегодовая» и «текущая» температура существенно: по
// среднегодовой определяются биомы (world::sampleBiome), а текущая
// температура и frost из неё управляют снегом в шейдере. Иначе зимой лес
// перекрашивался бы в тундру, а летом наоборот.

#include <cstddef>
#include <functional>

#include <glm/glm.hpp>

namespace world {

// Времена года. Порядок важен: индекс делит год на четыре равные части,
// фаза года [0, 1) — это season/4 плюс прогресс внутри сезона.
enum class Season : std::size_t {
    Spring = 0,
    Summer = 1,
    Autumn = 2,
    Winter = 3,
};

inline constexpr std::size_t kSeasonCount = 4;

// Имя сезона для логов и HUD.
const char* seasonName(Season season);

class Climate {
public:
    struct Config {
        // Длительность игрового года в реальных секундах. 600 с = 10 минут —
        // сезон тогда длится 2.5 минуты, что достаточно быстро, чтобы увидеть
        // смену времени года, и достаточно медленно, чтобы успеть рассмотреть
        // ландшафт.
        float yearLength{600.0f};
        // Сколько суток укладывается в год. Влияет только на скорость смены
        // освещения, к самому климату отношения не имеет.
        float daysPerYear{4.0f};
        // Стартовая фаза года [0, 1): 0 — начало весны, 0.25 — начало лета.
        // По умолчанию 0.05 — самое начало весны: снег в тундре и на вершинах
        // ещё лежит, а долины уже зелёные, то есть видно все биомы сразу.
        float startYearPhase{0.05f};
        // Стартовое время суток [0, 1): 0 — полночь, 0.25 — восход,
        // 0.5 — полдень. По умолчанию утро, чтобы первый кадр был освещён.
        float startTimeOfDay{0.35f};

        // Среднегодовая температура на уровне моря в центре карты, ℃.
        float baseTemperature{11.0f};
        // Полуразмах сезонных колебаний температуры: зимой base - amplitude,
        // летом base + amplitude.
        float seasonalAmplitude{11.0f};
        // Полуразмах суточных колебаний, ℃.
        float diurnalAmplitude{4.0f};
        // Падение температуры с высотой, ℃ на единицу мирового расстояния.
        // При amplitude = 26 вершина на +26 единицах холоднее низины на
        // 26 * lapseRate градусов.
        float lapseRate{0.28f};
        // Полуразмах широтного градиента, ℃: запад холоднее востока на
        // 2 * latitudeSpread градусов. Задаёт полосу пустыня -> лес -> тундра
        // поперёк карты: на западе холодно (тундра), на востоке жарко.
        float latitudeSpread{16.0f};
        // Базовая влажность и её сезонная амплитуда, 0..1. Влажность влияет на
        // биомы, но не на снег.
        float baseHumidity{0.45f};
        float humiditySeasonal{0.15f};
        // Полуразмах широтного градиента влажности, 0..1. Направлен против
        // температурного: восток жаркий И сухой (пустыня), запад холодный И
        // влажный (тундра). Именно пересечение двух градиентов и даёт все
        // четыре биома на одной карте.
        float humidityLatitudeSpread{0.25f};
        // Сколько влажности снимает каждая единица высоты (орографический
        // эффект: на вершинах суше, в долинах влажнее).
        float humidityAltitudeRate{0.006f};
    };

    // Два конструктора вместо `explicit Climate(Config = Config{})`: значение
    // по умолчанию вида Config{} в теле класса сослаться на ещё не завершённый
    // вложенный тип нельзя.
    Climate();
    explicit Climate(Config config);

    const Config& config() const noexcept { return config_; }

    // Сдвигает время на deltaTime реальных секунд: двигает фазу года и время
    // суток с переносом через границы. Внутри года и суток — линейно, без
    // скачка, поэтому сезоны меняются плавно.
    void update(float deltaTime);

    // Прыжок на произвольную фазу года [0, 1) и время суток [0, 1).
    // Обе фазы берутся по модулю 1, так что 5.25 — это то же, что 0.25.
    // Нужно для воспроизводимых скриншотов и отладки зимы/лета.
    void setTime(float yearPhase, float timeOfDay);

    // --- Календарь ---
    float yearProgress() const noexcept { return yearPhase_; }  // [0, 1)
    Season season() const noexcept;
    // Прогресс внутри текущего сезона, [0, 1).
    float seasonProgress() const noexcept;
    // Время суток, [0, 1): 0 — полночь, 0.25 — восход, 0.5 — полдень.
    float timeOfDay() const noexcept { return timeOfDay_; }
    // Реальные секунды в одном игровом годе.
    float yearLength() const noexcept { return config_.yearLength; }
    // Прошёл ли год целиком с момента запуска (для счётчика в HUD).
    float elapsedYears() const noexcept { return elapsedYears_; }

    // --- Климат ---
    // Текущая температура в центре карты на уровне моря, ℃.
    float temperature() const noexcept;
    // Текущая влажность, 0..1.
    float humidity() const noexcept;
    // Сезонная «морозность», 0..1: 0 — тепло (лето), 1 — крепкая зима.
    // Это то, чем шейдер управляет снегом: снег идёт там, где
    // frost + snowBias места > 1.
    float frost() const noexcept;

    // Температура в точке (x, z) с учётом сезона, высоты и времени суток, ℃.
    // Сезон по умолчанию — текущий.
    float temperatureAt(float x, float z) const;
    float temperatureAt(float x, float z, Season season) const;
    // Среднегодовая температура в точке (x, z) без суточной и сезонной
    // составляющих. Именно она передаётся в world::sampleBiome: от неё
    // зависит, какой биом растёт в этом месте, а не как он выглядит сегодня.
    float annualMeanTemperatureAt(float x, float z) const;
    // Влажность в точке (x, z), 0..1, на текущий сезон.
    float humidityAt(float x, float z) const;
    // Среднегодовая влажность: без сезонной составляющей, поэтому по ней
    // тоже выбирается биом (см. annualMeanTemperatureAt — по той же причине).
    float annualMeanHumidityAt(float x, float z) const;

    // --- Связь с ландшафтом ---
    // Источник высот для температурной поправки. Terrain вызывает setHeightSampler
    // со своей картой высот после генерации и обязательно сбрасывает его в
    // nullptr перед уничтожением: иначе климат остался бы со ссылкой на
    // освобождённую карту. Без сэмплера считается, что высоты нет.
    void setHeightSampler(std::function<float(float, float)> sampler);
    // Габариты мира по X и Z: по ним раскладывается широтный градиент.
    // Пока не заданы, широтного градиента нет. Сейчас градиент зависит только
    // от X (запад -> восток), но размер по Z тоже сохраняется, чтобы карту
    // можно было сделать не квадратной, не меняя сигнатуру.
    void setWorldSize(float sizeX, float sizeZ);

    // --- Освещение для шейдера ---
    // Единичный вектор НА солнце (в небо), а не на его источник света.
    glm::vec3 sunDirection() const noexcept;
    // Яркость солнца с учётом высоты солнца и сезона: ночью 0.
    float sunIntensity() const noexcept;
    // Заполняющий (ambient) свет: не даёт теням быть полностью чёрными.
    float ambient() const noexcept;

private:
    // Фаза года, при которой «температура = базовая» (половина весны), и
    // сезонное отклонение для произвольной фазы года, ℃.
    float seasonalOffset(float yearPhase) const noexcept;
    // Широтное отклонение точки (x, z), ℃: -latitudeSpread на западе,
    // +latitudeSpread на востоке.
    float latitudeOffset(float x, float z) const noexcept;
    // Нормированное положение точки по X: -1 на западе, +1 на востоке.
    // Общая часть широтных градиентов температуры и влажности.
    float latitudeFactor(float x) const noexcept;
    // Высота в точке из сэмплера (0, если сэмплера нет).
    float heightAt(float x, float z) const;
    // Суточное отклонение, ℃.
    float diurnalOffset() const noexcept;
    // Смена суток: 0 — ночь, 1 — день. Из высоты солнца, поэтому в сумереках
    // свет ещё есть, но уже приглушённый.
    float daylight() const noexcept;

    Config config_;
    // Фазы времени в [0, 1). yearPhase_ = 0 соответствует началу весны.
    float yearPhase_{0.0f};
    float timeOfDay_{0.0f};
    // Полные прошедшие годы (для HUD): растёт отдельно, чтобы фазы не
    // накапливали ошибку от сложения мелких шагов.
    float elapsedYears_{0.0f};
    std::function<float(float, float)> heightSampler_;
    float worldSizeX_{0.0f};
    float worldSizeZ_{0.0f};
};

}  // namespace world
